create extension if not exists unaccent;

alter table public.regions
  add column if not exists code text,
  add column if not exists slug text,
  add column if not exists is_active boolean not null default true;
create unique index if not exists regions_slug_uidx on public.regions(slug) where slug is not null;

create table if not exists public.districts (
  id uuid primary key default gen_random_uuid(),
  region_id uuid not null references public.regions(id) on delete restrict,
  code text,
  name text not null,
  slug text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(region_id, slug)
);

create table if not exists public.communes (
  id uuid primary key default gen_random_uuid(),
  district_id uuid not null references public.districts(id) on delete restrict,
  region_id uuid not null references public.regions(id) on delete restrict,
  code text,
  name text not null,
  slug text not null,
  city_id uuid references public.cities(id) on delete set null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(district_id, slug)
);

alter table public.cities
  add column if not exists district_id uuid references public.districts(id) on delete set null,
  add column if not exists commune_id uuid,
  add column if not exists slug text,
  add column if not exists aliases text[] not null default '{}',
  add column if not exists is_active boolean not null default true;

create index if not exists cities_region_idx on public.cities(region_id);
create index if not exists cities_district_idx on public.cities(district_id);
create index if not exists communes_region_idx on public.communes(region_id);
create index if not exists communes_district_idx on public.communes(district_id);

