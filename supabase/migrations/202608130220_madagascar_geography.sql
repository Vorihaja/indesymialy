-- Keep existing city UUIDs; add only missing region/name pairs.
insert into public.cities(name,region_id,district_id,slug,is_active)
select x.commune_name,x.region_id,x.district_id,x.commune_slug,true
from (
  select distinct on (r.id,lower(unaccent(s.commune_name)))
    r.id as region_id,d.id as district_id,s.commune_name,s.commune_slug
  from geography_stage s
  join public.regions r on r.slug=s.region_slug
  join public.districts d on d.region_id=r.id and d.slug=s.district_slug
  order by r.id,lower(unaccent(s.commune_name)),d.slug
) x
where not exists (
  select 1 from public.cities c
  where c.region_id=x.region_id and lower(unaccent(c.name))=lower(unaccent(x.commune_name))
);

update public.cities c
set district_id=x.district_id,slug=x.commune_slug,is_active=true
from (
  select distinct on (r.id,lower(unaccent(s.commune_name)))
    r.id as region_id,d.id as district_id,s.commune_name,s.commune_slug
  from geography_stage s
  join public.regions r on r.slug=s.region_slug
  join public.districts d on d.region_id=r.id and d.slug=s.district_slug
  order by r.id,lower(unaccent(s.commune_name)),d.slug
) x
where c.region_id=x.region_id and lower(unaccent(c.name))=lower(unaccent(x.commune_name));

insert into public.communes(region_id,district_id,name,slug,city_id,is_active)
select r.id,d.id,s.commune_name,s.commune_slug,c.id,true
from geography_stage s
join public.regions r on r.slug=s.region_slug
join public.districts d on d.region_id=r.id and d.slug=s.district_slug
join lateral (
  select city.id from public.cities city
  where city.region_id=r.id and lower(unaccent(city.name))=lower(unaccent(s.commune_name))
  order by city.created_at nulls last,city.id
  limit 1
) c on true
on conflict(district_id,slug) do update
set name=excluded.name,region_id=excluded.region_id,city_id=excluded.city_id,is_active=true;

update public.cities c
set commune_id=chosen.commune_id
from (
  select distinct on (city_id) city_id,id as commune_id
  from public.communes
  where city_id is not null
  order by city_id,slug,id
) chosen
where chosen.city_id=c.id and c.commune_id is null;

