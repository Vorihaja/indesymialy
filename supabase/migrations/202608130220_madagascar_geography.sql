insert into public.regions(name,slug,is_active)
select distinct s.region_name,s.region_slug,true
from geography_stage s
where not exists (
  select 1 from public.regions r
  where lower(unaccent(r.name))=lower(unaccent(s.region_name))
);

update public.regions r
set slug=s.region_slug,is_active=true
from (select distinct region_name,region_slug from geography_stage) s
where lower(unaccent(r.name))=lower(unaccent(s.region_name));

insert into public.districts(region_id,name,slug,is_active)
select distinct r.id,s.district_name,s.district_slug,true
from geography_stage s
join public.regions r on r.slug=s.region_slug
on conflict(region_id,slug) do update set name=excluded.name,is_active=true;

-- Repair the three pre-existing city rows that had no region.
update public.cities c set region_id=r.id,district_id=d.id,slug='anakao'
from public.regions r join public.districts d on d.region_id=r.id and d.slug='toliary-ii'
where lower(unaccent(c.name))='anakao' and c.region_id is null and r.slug='atsimo-andrefana';
update public.cities c set region_id=r.id,district_id=d.id,slug='tambohorano'
from public.regions r join public.districts d on d.region_id=r.id and d.slug='maintirano'
where lower(unaccent(c.name))='tambohorano' and c.region_id is null and r.slug='melaky';
